// Every voice of every tablature staff, without the drawing objects.
function tabStavesOf(visualObj) {
	var result = [];
	for (var i = 0; i < visualObj.lines.length; i++) {
		var staffs = visualObj.lines[i].staff;
		if (!staffs) continue;
		for (var s = 0; s < staffs.length; s++) {
			if (staffs[s].clef.type !== 'TAB') continue;
			for (var v = 0; v < staffs[s].voices.length; v++) {
				result.push(staffs[s].voices[v].map(function (el) {
					var copy = Object.assign({}, el);
					delete copy.abselem;
					return JSON.parse(JSON.stringify(copy));
				}));
			}
		}
	}
	return result;
}

function compareTabStaves(c, expected) {
	var options = { add_classes: true, tablature: JSON.parse(JSON.stringify(c.tab)) };
	if (c.params) {
		var keys = Object.keys(c.params);
		for (var k = 0; k < keys.length; k++)
			options[keys[k]] = c.params[keys[k]];
	}
	var visualObj = abcjs.renderAbc("paper", c.abc, options)[0];
	chai.assert.isUndefined(visualObj.warnings, "warnings: " + visualObj.warnings);
	var received = tabStavesOf(visualObj);
	chai.assert.equal(received.length, expected.length, "number of tablature staves");
	for (var i = 0; i < expected.length; i++) {
		chai.assert.equal(received[i].length, expected[i].length, "number of elements in staff " + i);
		for (var j = 0; j < expected[i].length; j++) {
			var msg = "\nstaff " + i + ", element " + j + "\nrcv: " + JSON.stringify(received[i][j]) + "\nexp: " + JSON.stringify(expected[i][j]) + "\n";
			chai.assert.deepStrictEqual(received[i][j], expected[i][j], msg);
		}
	}
}
